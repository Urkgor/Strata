#!/usr/bin/env python3
"""gen_iq_tables.py GGML_COMMON_H OUT.hpp - src/gemma4/g4_iq_tables.hpp: the code books of ggml's IQ2 / IQ3 formats and the MXFP4 values, copied from
llama.cpp's ggml/src/ggml-common.h (MIT) as plain arrays: a host copy and, under nvcc, a __constant__ one for the kernels."""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
want = ["kmask_iq2xs", "ksigns_iq2xs", "iq2xxs_grid", "iq2xs_grid", "iq2s_grid", "iq3xxs_grid", "iq3s_grid", "kvalues_fp4"]
out = ["// g4_iq_tables.hpp - generated by tools/gemma4/gen_iq_tables.py from llama.cpp's ggml-common.h (MIT).  Do not edit.",
       "#pragma once", "#include <cstdint>", "#include \"g4_compat.hpp\"", "", "namespace g4 {", "namespace tab {", ""]
for name in want:
    m = re.search(r"GGML_TABLE_BEGIN\((\w+),\s*%s,\s*(\w+)\)(.*?)GGML_TABLE_END\(\)" % name, src, re.S)
    typ, n, body = m.group(1), m.group(2), m.group(3)
    body = re.sub(r"//.*", "", body)
    vals = [v for v in re.split(r"[,\s]+", body.strip()) if v]
    assert len(vals) == int(n), (name, len(vals), n)
    ctype = {"uint8_t": "uint8_t", "uint32_t": "uint32_t", "uint64_t": "uint64_t", "int8_t": "int8_t"}[typ]
    if ctype == "uint64_t":
        vals = [v if v.endswith("ULL") or v.endswith("ull") else v + "ull" for v in vals]
    lines = []
    for i in range(0, len(vals), 8):
        lines.append("    " + ", ".join(vals[i:i + 8]) + ",")
    body = "\n".join(lines)
    out.append("static const %s %s_h[%s] = {\n%s\n};" % (ctype, name, n, body))
    out.append("#if defined(__CUDACC__)\nstatic __constant__ %s %s_d[%s] = {\n%s\n};\n#endif\n" % (ctype, name, n, body))
out += ["}  // namespace tab", "", "// one accessor per table: the device's constant memory under nvcc's device pass, the host array otherwise"]
for name, ctype in [("ksigns_iq2xs", "uint8_t"), ("iq2xxs_grid", "uint64_t"), ("iq2xs_grid", "uint64_t"), ("iq2s_grid", "uint64_t"), ("iq3xxs_grid", "uint32_t"),
                    ("iq3s_grid", "uint32_t"), ("kvalues_fp4", "int8_t")]:
    out.append("G4_HD %s %s(int i) {\n#if defined(__CUDA_ARCH__)\n    return tab::%s_d[i];\n#else\n    return tab::%s_h[i];\n#endif\n}" % (ctype, name, name, name))
out += ["", "}  // namespace g4", ""]
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out))
